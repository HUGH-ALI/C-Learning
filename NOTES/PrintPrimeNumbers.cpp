//打印100-200间的素数
//素数大于1，素数只能被1和自己整除。偶数只有2是素数。
//一个数的一对因子，一定有一个大于等于这个数开方，另一个一定小于等于这个数开方
//eg:12 2*6 3*4 ;所以只需要在这个数的开方前找出能整除这个数的数，那么后面一定有另一个数也可以整除他
//因此不必遍历所有数，只需要到这个数的开方就行了
int main()
{
	int i=100,count=0;
	for(i=101;i<=200;i+=2)
	{
		int flag=0,j=2;
		for(j=2;j*j<=i;j++)
		{
			if(i%j==0)
			{
				flag=1;
				break;
			}
		}
		if(!flag)
		{
			printf("%d ",i);
			count++;
		}
	}
	printf("\n共有%d个素数",count);
	return 0;
 } 
